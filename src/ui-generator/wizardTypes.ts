/**
 * Wizard Types
 */

import type { FieldRef } from "./fieldCatalog";

// Navigation placement config
export interface CustomSection {
  id: string;
  label: string;
  icon: string;
}

export interface NavigationConfig {
  parentSection: string | null;
  newSectionName: string;
  newSectionIcon: string;
  isNewSection: boolean;
  customSections: CustomSection[];
}

// Scope options
export type ScopeType = "specific-user" | "global-queue" | "both" | null;

// Primary view options
export type PrimaryViewType = "grid" | "table" | "grid-toggle" | "create-page" | null;

// Details open behavior
export type DetailsOpenType = "side-panel" | "modal" | "separate-page" | "none" | null;

// Filter options - dynamic based on selected fields
export interface FiltersConfig {
  freeTextSearch: boolean;
  // Dynamic filters based on selected table columns (fieldId -> enabled)
  fieldFilters: Record<string, boolean>;
}

// Row action options
export interface RowActionsConfig {
  viewDetails: boolean;
  edit: boolean;
  duplicate: boolean;
  approve: boolean;
  reject: boolean;
  rejectRequiresReason: boolean;
  delete: boolean;
}

// Bulk action options
export interface BulkActionsConfig {
  approveSelected: boolean;
  rejectSelected: boolean;
  rejectRequiresReason: boolean;
}

// Confirmation options
export interface ConfirmationsConfig {
  confirmDelete: boolean;
  confirmReject: boolean;
}

// Permission roles
export type PermissionRole = "admin" | "moderator" | "support" | "viewer";

// Permissions config
export interface PermissionsConfig {
  view: PermissionRole[];
  moderate: PermissionRole[];
  delete: PermissionRole[];
}

// Selected fields config
export interface SelectedFieldsConfig {
  tableColumns: FieldRef[];
  gridFields: FieldRef[];
  detailsFields: FieldRef[];
}

// Create Page configuration (P-03 Detail Editor)
export interface CreatePageConfig {
  propertiesPanel: {
    statusToggle: boolean;
    statusLabel: string;
    showDelete: boolean;
    detailsItems?: Array<
      | { id: string; kind: "field"; label: string; type: string; required?: boolean; readOnly?: boolean; autoGenerated?: boolean; placeholder?: string; copyable?: boolean }
      | { id: string; kind: "action"; label: string }
      | { id: string; kind: "section"; title: string }
    >;
    sections: {
      id: string;
      title: string;
      fields: {
        id: string;
        label: string;
        type: "input" | "textarea" | "select" | "date-time" | "readonly";
        required?: boolean;
        readOnly?: boolean;
        autoGenerated?: boolean;
        placeholder?: string;
        copyable?: boolean;
      }[];
    }[];
  };
  sections: {
    id: string;
    type: "form" | "accordion-list" | "editable-table" | "master-detail" | "media-upload" | "simple-list";
    title: string;
    config: Record<string, unknown>;
  }[];
  saveChanges: boolean;
  saveAndClose: boolean;
  showToolbar: boolean;
}

// Full wizard intent object
export interface WizardIntent {
  featureId: string;
  title: string;
  description: string;
  navigation: NavigationConfig;
  createPageConfig: CreatePageConfig;
  selectedFields: SelectedFieldsConfig;
  filters: FiltersConfig;
  rowActions: RowActionsConfig;
  bulkActions: BulkActionsConfig;
  // Legacy fields — kept optional for backward compat with stored data
  scope?: ScopeType;
  primaryView?: PrimaryViewType;
  detailsOpen?: DetailsOpenType;
  confirmations?: ConfirmationsConfig;
  permissions?: PermissionsConfig;
}

// Wizard step definition
export interface WizardStep {
  id: number;
  title: string;
  description: string;
}

